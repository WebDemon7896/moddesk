"""ModDesk Setup - installs (or updates) ModDesk, and uninstalls it with:  ModDesk-Setup.exe --uninstall

The program files travel inside this exe as payload.zip (built by build.bat). Installing over an existing
install only replaces program files: profiles, app.json, apis.json and crash logs are never touched.
Generated by AI (Claude, made by Anthropic).
"""
import ast
import io
import os
import shutil
import subprocess
import sys
import tkinter as tk
import zipfile
from tkinter import filedialog, messagebox, ttk

APP = "ModDesk"
UNINSTALL_KEY = r"Software\Microsoft\Windows\CurrentVersion\Uninstall\ModDesk"
KEEP = ("profiles", "app.json", "apis.json", "settings.json", "data", "browser-data", "responses", "crash.log")
NO_WINDOW = 0x08000000


def resource(name):
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, name)


def payload():
    return zipfile.ZipFile(resource("payload.zip"))


def read_terms(z):
    """TERMS_TEXT lives in app/moddesk.py inside the payload, so the installer shows the same text as the app."""
    try:
        tree = ast.parse(z.read("app/moddesk.py").decode("utf-8"))
        for n in tree.body:
            if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "TERMS_TEXT":
                return ast.literal_eval(n.value)
    except Exception:  # noqa
        pass
    return "Use ModDesk only for legitimate moderation work.\n\nGenerated by AI."


def payload_version(z):
    try:
        for line in z.read("app/moddesk.py").decode("utf-8").splitlines():
            if line.startswith("APP_VERSION"):
                return line.split('"')[1]
    except Exception:  # noqa
        pass
    return ""


def payload_repo(z):
    try:
        tree = ast.parse(z.read("app/moddesk.py").decode("utf-8"))
        for n in tree.body:
            if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "DEFAULT_UPDATE_REPO":
                return ast.literal_eval(n.value)
    except Exception:  # noqa
        pass
    return ""


def ver_tuple(v):
    import re
    return tuple(int(x) for x in re.findall(r"\d+", str(v))[:4]) or (0,)


def newest_from_github(z, folder, progress):
    """If the payload names a GitHub repo, grab its newest moddesk.py so a months-old Setup still installs fresh code."""
    repo = payload_repo(z)
    if not repo:
        return payload_version(z)
    try:
        import urllib.request
        url = "https://raw.githubusercontent.com/%s/main/moddesk.py" % repo
        req = urllib.request.Request(url, headers={"User-Agent": "ModDesk-Setup"})
        src = urllib.request.urlopen(req, timeout=10).read().decode("utf-8")
        compile(src, "moddesk.py", "exec")
        new_v = ""
        for line in src.splitlines():
            if line.startswith("APP_VERSION"):
                new_v = line.split('"')[1]
        if new_v and ver_tuple(new_v) > ver_tuple(payload_version(z)) and "class App" in src:
            progress(100, "Newest code from GitHub (%s)" % new_v)
            with open(os.path.join(folder, "app", "moddesk.py"), "w", encoding="utf-8", newline="") as f:
                f.write(src)
            return new_v
    except Exception:  # noqa - offline or no repo: the bundled code is fine
        pass
    return payload_version(z)


def default_dir():
    return os.path.join(os.environ.get("LOCALAPPDATA", os.path.expanduser("~")), "Programs", APP)


def start_menu_dir():
    return os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows", "Start Menu", "Programs")


def desktop_dir():
    return os.path.join(os.environ.get("USERPROFILE", os.path.expanduser("~")), "Desktop")


def make_shortcut(path, target, workdir, icon):
    ps = ("$s=(New-Object -COM WScript.Shell).CreateShortcut('%s');$s.TargetPath='%s';$s.WorkingDirectory='%s';"
          "$s.IconLocation='%s';$s.Save()") % tuple(x.replace("'", "''") for x in (path, target, workdir, icon))
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], creationflags=NO_WINDOW, check=True, timeout=60)


def register_uninstall(folder, version):
    try:
        import winreg
        with winreg.CreateKey(winreg.HKEY_CURRENT_USER, UNINSTALL_KEY) as k:
            winreg.SetValueEx(k, "DisplayName", 0, winreg.REG_SZ, APP)
            winreg.SetValueEx(k, "DisplayVersion", 0, winreg.REG_SZ, version or "")
            winreg.SetValueEx(k, "InstallLocation", 0, winreg.REG_SZ, folder)
            winreg.SetValueEx(k, "DisplayIcon", 0, winreg.REG_SZ, os.path.join(folder, "ModDesk.exe"))
            winreg.SetValueEx(k, "UninstallString", 0, winreg.REG_SZ,
                              '"%s" --uninstall' % os.path.join(folder, "ModDesk-Setup.exe"))
            winreg.SetValueEx(k, "NoModify", 0, winreg.REG_DWORD, 1)
    except Exception:  # noqa - not Windows
        pass


def install(folder, shortcuts, progress):
    """Extract the payload into folder. Returns the version installed."""
    z = payload()
    names = [n for n in z.namelist() if not n.endswith("/")]  # entries use forward slashes (make_payload.py)
    os.makedirs(folder, exist_ok=True)
    for i, name in enumerate(names):
        top = name.split("/")[0]
        dest = os.path.join(folder, *name.split("/"))
        if top in KEEP and os.path.exists(dest):
            continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with z.open(name) as src, open(dest, "wb") as out:
            shutil.copyfileobj(src, out)
        progress((i + 1) * 100 // len(names), name)
    version = newest_from_github(z, folder, progress)
    if getattr(sys, "frozen", False):
        try:
            shutil.copy(sys.executable, os.path.join(folder, "ModDesk-Setup.exe"))  # used for uninstall / repair
        except OSError:
            pass
    exe = os.path.join(folder, "ModDesk.exe")
    icon = os.path.join(folder, "icon.ico")
    if shortcuts.get("start"):
        make_shortcut(os.path.join(start_menu_dir(), "ModDesk.lnk"), exe, folder, icon if os.path.exists(icon) else exe)
    if shortcuts.get("desktop"):
        make_shortcut(os.path.join(desktop_dir(), "ModDesk.lnk"), exe, folder, icon if os.path.exists(icon) else exe)
    register_uninstall(folder, version)
    return version


class Setup(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("ModDesk Setup")
        self.geometry("640x520")
        self.resizable(False, False)
        try:
            self.iconbitmap(resource("icon.ico"))
        except tk.TclError:
            pass
        self.z = payload()
        self.version = payload_version(self.z)
        self.accept = tk.BooleanVar(value=False)
        self.folder = tk.StringVar(value=default_dir())
        self.start = tk.BooleanVar(value=True)
        self.desktop = tk.BooleanVar(value=False)
        self.pin = tk.BooleanVar(value=True)
        self.launch = tk.BooleanVar(value=True)
        self.body = ttk.Frame(self, padding=14)
        self.body.pack(fill="both", expand=True)
        bar = ttk.Frame(self, padding=(14, 0, 14, 12))
        bar.pack(fill="x")
        self.back_btn = ttk.Button(bar, text="Back", command=self.prev)
        self.next_btn = ttk.Button(bar, text="Next", command=self.nxt)
        self.cancel_btn = ttk.Button(bar, text="Cancel", command=self.destroy)
        self.next_btn.pack(side="right")
        self.cancel_btn.pack(side="right", padx=6)
        self.back_btn.pack(side="left")
        self.pages = [self.p_terms, self.p_folder, self.p_options, self.p_install, self.p_done]
        self.i = 0
        self.accept.trace_add("write", lambda *a: self.buttons())
        self.show()

    def clear(self):
        for w in self.body.winfo_children():
            w.destroy()

    def head(self, title, sub=""):
        ttk.Label(self.body, text=title, font=("Segoe UI", 14, "bold")).pack(anchor="w")
        if sub:
            ttk.Label(self.body, text=sub, foreground="#555", wraplength=590, justify="left").pack(
                anchor="w", pady=(2, 8))

    def show(self):
        self.clear()
        self.pages[self.i]()
        self.buttons()

    def buttons(self):
        self.next_btn.configure(text={2: "Install", 4: "Finish"}.get(self.i, "Next"))
        ok = not (self.i == 0 and not self.accept.get())
        self.next_btn.configure(state="normal" if ok else "disabled")
        self.back_btn.configure(state="normal" if 0 < self.i < 3 else "disabled")
        self.cancel_btn.configure(state="disabled" if self.i in (3, 4) else "normal")

    def p_terms(self):
        self.head("ModDesk %s" % self.version, "Read what ModDesk is for - and not for - before installing.")
        fr = ttk.Frame(self.body)
        fr.pack(fill="both", expand=True)
        txt = tk.Text(fr, wrap="word", padx=8, pady=6, relief="solid", borderwidth=1, height=16)
        sb = ttk.Scrollbar(fr, command=txt.yview)
        txt.configure(yscrollcommand=sb.set)
        sb.pack(side="right", fill="y")
        txt.pack(side="left", fill="both", expand=True)
        txt.insert("1.0", read_terms(self.z))
        txt.configure(state="disabled")
        ttk.Checkbutton(self.body, text="I accept (legitimate moderation use only)", variable=self.accept).pack(
            anchor="w", pady=(8, 0))

    def existing(self):
        return os.path.exists(os.path.join(self.folder.get(), "ModDesk.exe"))

    def p_folder(self):
        self.head("Where to install", "Pick any folder you can write to. The default needs no administrator rights.")
        row = ttk.Frame(self.body)
        row.pack(fill="x", pady=8)
        ttk.Entry(row, textvariable=self.folder).pack(side="left", fill="x", expand=True)
        ttk.Button(row, text="Browse...", command=self.browse).pack(side="left", padx=6)
        self.note = ttk.Label(self.body, wraplength=590, justify="left", foreground="#0a5")
        self.note.pack(anchor="w", pady=10)
        self.folder.trace_add("write", lambda *a: self.refresh_note())
        self.refresh_note()

    def refresh_note(self):
        try:
            self.note.configure(text=("An existing ModDesk was found here: this will UPDATE it. Your profiles, "
                                      "keys and settings are kept.") if self.existing()
                                else "A new copy of ModDesk will be installed here.")
        except tk.TclError:
            pass

    def browse(self):
        d = filedialog.askdirectory(title="Install ModDesk into...", initialdir=self.folder.get() or None)
        if d:
            name = os.path.basename(os.path.normpath(d))
            self.folder.set(os.path.normpath(d if name.lower() == "moddesk" or os.listdir(d) == [] else
                                             os.path.join(d, "ModDesk")))

    def p_options(self):
        self.head("Shortcuts", "Choose where ModDesk should appear.")
        ttk.Checkbutton(self.body, text="Add to the Start menu", variable=self.start).pack(anchor="w", pady=3)
        ttk.Checkbutton(self.body, text="Put a shortcut on the Desktop", variable=self.desktop).pack(anchor="w", pady=3)
        ttk.Checkbutton(self.body, text="Help me pin it to the taskbar / Start afterwards",
                        variable=self.pin).pack(anchor="w", pady=3)
        ttk.Label(self.body, foreground="#555", wraplength=590, justify="left",
                  text="Windows does not let installers pin things by themselves. With this ticked I open the "
                       "folder holding the ModDesk shortcut at the end: right-click it (Show more options on "
                       "Windows 11) and choose Pin to taskbar or Pin to Start. Pin the SHORTCUT or ModDesk.exe "
                       "once and updates will never lose it.").pack(anchor="w", pady=14)

    def p_install(self):
        self.head("Installing...", "")
        self.bar = ttk.Progressbar(self.body, maximum=100)
        self.bar.pack(fill="x", pady=10)
        self.line = ttk.Label(self.body, text="", foreground="#555")
        self.line.pack(anchor="w")
        self.after(200, self.run_install)

    def run_install(self):
        def progress(pct, name):
            self.bar["value"] = pct
            self.line.configure(text=name)
            self.update_idletasks()
        while True:
            try:
                self.installed = install(os.path.normpath(self.folder.get()),
                                         {"start": self.start.get(), "desktop": self.desktop.get()}, progress)
                break
            except PermissionError as e:
                if not messagebox.askretrycancel("ModDesk Setup", "A file is in use (is ModDesk still running?).\n"
                                                                  "Close it and press Retry.\n\n%s" % e):
                    self.destroy()
                    return
            except Exception as e:  # noqa
                messagebox.showerror("ModDesk Setup", "Install failed:\n%s" % e)
                self.destroy()
                return
        self.i = 4
        self.show()

    def p_done(self):
        self.head("ModDesk is installed", "Version %s in %s" % (self.version, self.folder.get()))
        ttk.Checkbutton(self.body, text="Start ModDesk now", variable=self.launch).pack(anchor="w", pady=10)
        ttk.Label(self.body, foreground="#555", wraplength=590, justify="left",
                  text="To update later: run this Setup again (it keeps your data), or use Settings > Updates in "
                       "ModDesk. To uninstall: Windows Settings > Apps, or run ModDesk-Setup.exe --uninstall from the "
                       "install folder.\n\nGenerated by AI (Claude, made by Anthropic).").pack(anchor="w")

    def prev(self):
        if 0 < self.i < 3:
            self.i -= 1
            self.show()

    def nxt(self):
        if self.i == 1:
            f = os.path.normpath(self.folder.get().strip())
            if not f or not os.path.isabs(f):
                messagebox.showinfo("ModDesk Setup", "Pick a full folder path.")
                return
            self.folder.set(f)
        if self.i == 4:
            self.finish()
            return
        self.i += 1
        self.show()

    def finish(self):
        folder = os.path.normpath(self.folder.get())
        if self.pin.get() and self.start.get():
            try:
                os.startfile(start_menu_dir())  # noqa
            except (OSError, AttributeError):
                pass
        elif self.pin.get():
            try:
                os.startfile(folder)  # noqa
            except (OSError, AttributeError):
                pass
        if self.launch.get():
            try:
                subprocess.Popen([os.path.join(folder, "ModDesk.exe")], cwd=folder)
            except OSError:
                pass
        self.destroy()


def uninstall():
    root = tk.Tk()
    root.withdraw()
    folder = os.path.dirname(os.path.abspath(sys.executable if getattr(sys, "frozen", False) else __file__))
    if not os.path.exists(os.path.join(folder, "ModDesk.exe")):
        messagebox.showerror("ModDesk Setup", "Run this from the ModDesk install folder.")
        return
    if not messagebox.askyesno("Uninstall ModDesk", "Remove ModDesk from\n%s ?" % folder):
        return
    keep = messagebox.askyesno("Uninstall ModDesk", "Keep your profiles, keys and settings?\n\n"
                               "Yes = they stay in the folder so a later install picks them up.\n"
                               "No = everything in the folder is deleted.")
    for p in (os.path.join(start_menu_dir(), "ModDesk.lnk"), os.path.join(desktop_dir(), "ModDesk.lnk")):
        try:
            os.remove(p)
        except OSError:
            pass
    try:
        import winreg
        winreg.DeleteKey(winreg.HKEY_CURRENT_USER, UNINSTALL_KEY)
    except Exception:  # noqa
        pass
    me = os.path.abspath(sys.executable if getattr(sys, "frozen", False) else __file__)
    if keep:
        for name in os.listdir(folder):
            full = os.path.join(folder, name)
            if name in KEEP or os.path.abspath(full) == me:
                continue
            try:
                shutil.rmtree(full) if os.path.isdir(full) else os.remove(full)
            except OSError:
                pass
        cmd = 'cmd /c ping -n 3 127.0.0.1 >nul & del /q "%s"' % me   # this exe can only delete itself after exiting
    else:
        cmd = 'cmd /c ping -n 3 127.0.0.1 >nul & rmdir /s /q "%s"' % folder
    subprocess.Popen(cmd, shell=True, creationflags=NO_WINDOW)
    messagebox.showinfo("Uninstall ModDesk", "ModDesk was removed.")


if __name__ == "__main__":
    if "--uninstall" in sys.argv:
        uninstall()
    else:
        Setup().mainloop()
